# ————————————————— سؤالات تستی جزوه‌ها —————————————————
def mcq(cat, src, prefix, n, q, a_correct, wrongs, refs=None):
    """جای گزینهٔ درست بین الف/ب/ج/د می‌چرخد تا الگوی قابل حدس ساخته نشود."""
    letters = ["الف", "ب", "ج", "د"]
    pos = (n - 1) % 4
    items = wrongs[:pos] + [a_correct] + wrongs[pos:]
    return {
        "n": n, "q": q,
        "opts": {letters[i]: items[i] for i in range(4)},
        "ans": letters[pos], "ans_text": a_correct,
        "refs": refs or ["متن جزوه"], "src": src, "cat": cat,
        "quality": "ok", "dup": 0, "id": f"m-{prefix}-{n:02d}",
    }

def qa(cat, src, prefix, n, q, a, refs=None):
    return {
        "n": None, "q": q, "a": a, "refs": refs or ["متن جزوه"],
        "src": src, "cat": cat, "quality": "ok", "dup": 0,
        "id": f"q-{prefix}-{n:02d}",
    }

